import express from "express";
import fs from "fs";
import path from "path";
import {
  fileURLToPath,
} from "url";

import Booking from "../models/Booking.js";

import {
  protect,
  authorize,
} from "../middleware/authMiddleware.js";

const router = express.Router();

const __filename =
  fileURLToPath(
    import.meta.url
  );

const __dirname =
  path.dirname(
    __filename
  );

const documentDirectory =
  path.join(
    __dirname,
    "..",
    "uploads",
    "booking-documents"
  );

/* =====================================================
   ADMIN VIEW BOOKING DOCUMENT

   GET:
   /api/booking-documents/:bookingId/project-proposal

   GET:
   /api/booking-documents/:bookingId/approved-arf
===================================================== */

router.get(
  "/:bookingId/:documentType",
  protect,
  authorize("admin"),
  async (req, res) => {
    try {
      const {
        bookingId,
        documentType,
      } = req.params;

      const booking =
        await Booking.findById(
          bookingId
        );

      if (!booking) {
        return res
          .status(404)
          .json({
            message:
              "Booking not found.",
          });
      }

      let document = null;

      if (
        documentType ===
        "project-proposal"
      ) {
        document =
          booking.projectProposalFile;
      }

      if (
        documentType ===
        "approved-arf"
      ) {
        document =
          booking.approvedArfFile;
      }

      if (
        !document ||
        !document.fileName
      ) {
        return res
          .status(404)
          .json({
            message:
              "Document not found for this booking.",
          });
      }

      /*
        fileName was generated by our
        backend during upload.

        basename prevents path traversal.
      */

      const safeFileName =
        path.basename(
          document.fileName
        );

      const filePath =
        path.join(
          documentDirectory,
          safeFileName
        );

      if (
        !fs.existsSync(
          filePath
        )
      ) {
        return res
          .status(404)
          .json({
            message:
              "The uploaded document file could not be found.",
          });
      }

      const safeOriginalName =
        String(
          document.originalName ||
          safeFileName
        )
          .replace(
            /"/g,
            ""
          )
          .replace(
            /[\r\n]/g,
            ""
          );

      res.setHeader(
        "Content-Type",
        document.mimeType ||
          "application/octet-stream"
      );

      /*
        inline allows PDF/images to
        display inside a new browser tab.
      */

      res.setHeader(
        "Content-Disposition",
        `inline; filename="${safeOriginalName}"`
      );

      return res.sendFile(
        filePath
      );
    } catch (error) {
      console.error(
        "View booking document error:",
        error
      );

      return res
        .status(500)
        .json({
          message:
            "Unable to open booking document.",
        });
    }
  }
);

export default router;